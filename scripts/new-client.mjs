  // client needs something different from the "${category}" preset default.
  // tagline: "TODO: short tagline for this business",
  // about: "TODO: a paragraph about this business",
  // offerings: [
  //   { name: "TODO: item/service name", description: "TODO: description", price: "TODO: $price" },
  // ],
  // reviews: [
  //   { author: "TODO: reviewer name", rating: 5, text: "TODO: review text" },
  // ],
  // gallery: [
  //   { src: "TODO: image path/URL", alt: "TODO: alt text" },
